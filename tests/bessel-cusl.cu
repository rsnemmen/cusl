/*
  Testing the CUSL Bessel implementations
*/

#include <stdio.h>
#include <stdlib.h>
#include <curand_kernel.h>
#include "cusl_math.h"
#include "cheb_eval.cuh"
#include "poly.cuh"
#include "psi.cuh"
#include "gamma.cuh"
#include "bessel.cuh"

#define TPB 64

#define N 100
#define x0 0.1
#define x1 20.
#define filename "bessel-cuda-cusl.dat"
/* The corresponding GSL values are located in column 2 of the file
   bessel-gsl.dat generated by bessel-gsl.c
*/


#define CUDA_CHECK(call) do { \
	cudaError_t err = (call); \
	if (err != cudaSuccess) { \
		fprintf(stderr, "CUDA error %s:%d: %s\n", __FILE__, __LINE__, cudaGetErrorString(err)); \
		exit(1); \
	} \
} while (0)


__global__ void bessel(double *x, double *K0, double *K1, double *K2, double *K3, double *K4, double *K5, int n){
	int id = blockIdx.x*blockDim.x + threadIdx.x;

	if (id>=n) return;

	K0[id] =cu_sf_bessel_K0_scaled_e(x[id]);
	K1[id] =cu_sf_bessel_K1_scaled_e(x[id]);
	K2[id] =cu_sf_bessel_Kn(2,x[id]);
	K3[id] =cu_sf_bessel_Kn(3,x[id]);
	K4[id] =cu_sf_bessel_Kn(4,x[id]);
	K5[id] =cu_sf_bessel_Kn(5,x[id]);
}



int main(int argc, char *argv[]){
	int i;
	double *x, *K0, *K1, *K2, *K3, *K4, *K5;

	// Allocate Unified Memory - accessible from CPU or GPU
	CUDA_CHECK(cudaMallocManaged(&x, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K0, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K1, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K2, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K3, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K4, N*sizeof(double)));
	CUDA_CHECK(cudaMallocManaged(&K5, N*sizeof(double)));

	for (i=0; i<N; i++) {
		// generate array of x-values
		x[i]=x0+i*(x1-x0)/(N-1);
	}

	// kernel launch
    printf("Computing Bessel function on the GPU\n");
	bessel<<<(N+TPB-1)/TPB, TPB>>>(x, K0, K1, K2, K3, K4, K5, N);
	CUDA_CHECK(cudaGetLastError());

	// Wait for GPU to finish before accessing on host
	CUDA_CHECK(cudaDeviceSynchronize());

	// write file
	printf("Saving file %s\n", filename);
    FILE *f = fopen(filename, "w");
    if (f == NULL) {
        printf("Error opening file!\n");
        exit(1);
    }

    fprintf(f, "# x K0_scaled K1_scaled K2 K3 K4 K5\n");
    for (i=0; i<N; i++) {
        fprintf(f, "%f %f %f %f %f %f %f\n", x[i], K0[i], K1[i], K2[i], K3[i], K4[i], K5[i]);
    }

    // clean up
    fclose(f);
    CUDA_CHECK(cudaFree(x));
    CUDA_CHECK(cudaFree(K0));
	CUDA_CHECK(cudaFree(K1));
	CUDA_CHECK(cudaFree(K2));
	CUDA_CHECK(cudaFree(K3));
	CUDA_CHECK(cudaFree(K4));
	CUDA_CHECK(cudaFree(K5));

	return 0;
}
